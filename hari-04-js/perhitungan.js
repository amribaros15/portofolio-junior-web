const jariJari = 7;
const phi = 3.14;

const luasLingkaran = phi * jariJari * jariJari;
const kelilingLingkaran = 2 * phi * jariJari;

const detikPerHari = 24 * 60 * 60;

const celsius = 30;
const fahrenheit = (celsius * 9 / 5) + 32;

console.log("Luas Lingkaran:", luasLingkaran);
console.log("Keliling Lingkaran:", kelilingLingkaran);
console.log("Jumlah Detik dalam 1 Hari:", detikPerHari);
console.log("30°C dalam Fahrenheit:", fahrenheit);